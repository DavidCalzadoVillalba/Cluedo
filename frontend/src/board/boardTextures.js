export function assignTexture(cellIds, texture) {
   const ids = Array.isArray(cellIds) ? cellIds : [cellIds];
   return Object.fromEntries(ids.map((id) => [String(id), texture]));
}

export function assignRange(start, end, texture) {
   const ids = Array.from({ length: Math.max(0, end - start + 1) }, (_, index) => start + index);
   return assignTexture(ids, texture);
}

